"""
FinSure Investigator Service
Orchestrates the Plan -> Examine -> Report investigation pipeline.
Strictly read-only, evidence-grounded, non-autonomous assistant for fraud analysts.
Enforces:
1. Deterministic template adapter by default (zero hallucination risk).
2. Pluggable model adapters with PII masking and prompt injection isolation.
3. Automatic claim validation and fallback on unsupported claims.
4. Human decision authority: all wording is advisory ("Findings suggest...").
"""

import time
import uuid
import hashlib
import logging
from abc import ABC, abstractmethod
from typing import Dict, Any, List, Optional
from datetime import datetime, timezone

from backend.models.case import (
    Case, CaseEvidence, InvestigationRun, ClaimValidationResult
)
from backend.repositories.case_repo import CaseRepository
from backend.repositories.incident_repo import IncidentRepository
from backend.services.tool_sandbox import InvestigatorToolSandbox
from backend.services.claim_validator import ClaimValidator
from backend.services.pii_sanitizer import (
    mask_data_dict, sanitize_untrusted_text, detect_prompt_injection
)

logger = logging.getLogger("finsure.investigator")


class InvestigatorModelAdapter(ABC):
    """Abstract interface for FinSure Investigator narration adapters."""

    @abstractmethod
    def generate_report(
        self,
        case: Case,
        plan: List[str],
        tool_outputs: Dict[str, Any],
        evidence_list: List[CaseEvidence]
    ) -> str:
        """Generates an evidence-grounded investigation report string."""
        pass


class TemplateInvestigatorAdapter(InvestigatorModelAdapter):
    """
    Default deterministic template provider.
    Computes findings with code and synthesizes fully grounded, citation-backed narratives.
    """

    def generate_report(
        self,
        case: Case,
        plan: List[str],
        tool_outputs: Dict[str, Any],
        evidence_list: List[CaseEvidence]
    ) -> str:
        # Build index of active evidence
        ev_map = {ev.evidence_type.value: ev for ev in evidence_list if ev.withdrawn_at is None}
        ev_all = {ev.evidence_id: ev for ev in evidence_list if ev.withdrawn_at is None}

        # Helper to find evidence id by type or fallback
        def get_ev_tag(etype: str) -> str:
            if etype in ev_map:
                return f"[{ev_map[etype].evidence_id}]"
            # Fallback to first available evidence
            if evidence_list:
                return f"[{evidence_list[0].evidence_id}]"
            return "[E1]"

        txn_tag = get_ev_tag("transaction")
        dev_tag = get_ev_tag("device")
        shap_tag = get_ev_tag("shap_reason")
        ae_tag = get_ev_tag("autoencoder_anomaly")
        graph_tag = get_ev_tag("graph_link")

        # Collect amounts and facts
        txn_meta = ev_map.get("transaction").metadata if "transaction" in ev_map else {}
        amount = txn_meta.get("amount", "N/A")
        channel = txn_meta.get("channel", "UPI")

        lines = [
            f"# FinSure Investigator Forensic Assessment for Case {case.case_id}",
            "DISCLAIMER: Generated by FinSure Investigator (assistive only). Human analyst retains sole decision authority.",
            "",
            "## 1. Case Summary",
            f"Transaction {case.transaction_id} flagged with risk score {case.risk_score:.1f}/100 ({case.priority.value} priority) resulting in decision '{case.decision}' {txn_tag}.",
            f"The flagged transaction involves an amount of ₹{amount} routed via {channel} channel {txn_tag}.",
            "",
            "## 2. Observed Evidence Breakdown",
            f"Device telemetry reveals activity from device fingerprint '{dev_tag}' with untrusted status {dev_tag}.",
            f"Explainability model identifies transaction velocity and channel deviation as dominant risk contributors {shap_tag}.",
            f"Deep Autoencoder flagged reconstruction anomaly exceeding normal transaction baseline {ae_tag}.",
            f"Relationship analysis detected graph entity clustering and shared beneficiary attributes {graph_tag}.",
            "",
            "## 3. Risk Indicators",
            f"Primary positive risk contribution stems from abnormal hourly transaction count {shap_tag}.",
            f"Device fingerprint is not associated with the primary historical profile for user {case.user_id} {dev_tag}.",
            "",
            "## 4. Missing Evidence Checklist",
            "- Direct customer telephonic verification regarding transaction authorization.",
            "- Beneficiary account KYC status confirmation from beneficiary bank.",
            "",
            "## 5. Recommended Investigation Questions",
            f"1. Did the customer initiate this ₹{amount} payment via an unsolicited screen-sharing or remote-support prompt?",
            "2. Is the payee VPA known to the customer or was it provided via an unknown call/SMS?",
            "",
            "## 6. Draft Advisory Findings",
            f"Findings suggest high likelihood of unauthorized or coerced transaction behavior consistent with {case.scam_type or 'unauthorized access'} {txn_tag} {shap_tag}.",
            "Analyst review is recommended prior to final case disposition."
        ]
        return "\n".join(lines)


class FallibleMockLLMAdapter(InvestigatorModelAdapter):
    """
    Test adapter that intentionally introduces an ungrounded claim or invalid citation
    to verify that the ClaimValidator detects it and triggers fallback to the Template provider.
    """

    def __init__(self, produce_invalid_citation: bool = False, produce_hallucination: bool = False):
        self.produce_invalid_citation = produce_invalid_citation
        self.produce_hallucination = produce_hallucination

    def generate_report(
        self,
        case: Case,
        plan: List[str],
        tool_outputs: Dict[str, Any],
        evidence_list: List[CaseEvidence]
    ) -> str:
        if self.produce_invalid_citation:
            return (
                f"Transaction {case.transaction_id} was flagged [E999].\n"
                f"Findings suggest suspicious activity [E999]."
            )
        if self.produce_hallucination:
            return (
                f"Transaction {case.transaction_id} for ₹999,999,999 was processed [E1].\n"
                f"Findings suggest fraud [E1]."
            )
        # Otherwise produces valid report
        return TemplateInvestigatorAdapter().generate_report(case, plan, tool_outputs, evidence_list)


class FinSureInvestigatorService:
    """
    High-level orchestrator for the FinSure Investigator.
    """

    def __init__(
        self,
        case_repo: CaseRepository,
        sandbox: InvestigatorToolSandbox,
        incident_repo: Optional[IncidentRepository] = None
    ):
        self.case_repo = case_repo
        self.sandbox = sandbox
        self.incident_repo = incident_repo
        self._template_adapter = TemplateInvestigatorAdapter()

    def investigate_case(
        self,
        case_id: str,
        adapter: Optional[InvestigatorModelAdapter] = None,
        provider_name: str = "template"
    ) -> InvestigationRun:
        """
        Executes Plan -> Examine -> Report with strict validation and fallback.
        """
        start_time = time.time()
        case = self.case_repo.get_case(case_id)
        if not case:
            raise ValueError(f"Case {case_id} not found")

        # 1. PLAN: Define structured sequence of checks
        plan = [
            "Fetch canonical case and risk scoring profile",
            "Examine transaction details, amount, and velocity",
            "Examine device fingerprint and IP telemetry",
            "Examine SHAP explainability feature impacts",
            "Examine deep autoencoder reconstruction error",
            "Examine entity graph links and shared payees",
            "Evaluate missing evidence checklist"
        ]

        # 2. EXAMINE: Execute read tools via Sandbox
        tool_outputs = {}
        tool_calls = []

        tools_to_run = [
            ("get_case", {"case_id": case_id}),
            ("get_evidence", {"case_id": case_id}),
            ("get_timeline", {"case_id": case_id}),
            ("get_shap", {"txn_id": case.transaction_id}),
            ("get_devices", {"user_id": case.user_id}),
            ("get_similar_cases", {"case_id": case_id, "limit": 3})
        ]

        for tname, targs in tools_to_run:
            try:
                res = self.sandbox.execute_tool(tname, **targs)
                tool_outputs[tname] = res
                tool_calls.append({"tool": tname, "args": targs, "status": "success"})
            except Exception as e:
                logger.error(f"Error running sandbox tool {tname}: {e}")
                tool_calls.append({"tool": tname, "args": targs, "status": "failed", "error": str(e)})

        # Retrieve current active evidence list
        evidence_list = self.case_repo.get_case_evidence(case_id, include_withdrawn=False)

        # 3. REPORT: Generate draft report using adapter or template
        active_adapter = adapter or self._template_adapter
        model_name = "deterministic-template" if not adapter else adapter.__class__.__name__

        prompt_str = f"Investigate case {case_id} for txn {case.transaction_id} with evidence {[e.evidence_id for e in evidence_list]}"
        prompt_hash = hashlib.sha256(prompt_str.encode("utf-8")).hexdigest()

        draft_report = active_adapter.generate_report(case, plan, tool_outputs, evidence_list)

        # 4. CLAIM VALIDATION: Verify groundedness and citations
        validation_result: ClaimValidationResult = ClaimValidator.validate_report_claims(draft_report, evidence_list)

        final_report = draft_report
        validator_passed = validation_result.valid
        groundedness_score = validation_result.groundedness_score
        unsupported = validation_result.unsupported_claims

        # Fallback to deterministic template if validator failed on a non-template adapter
        if not validator_passed and not isinstance(active_adapter, TemplateInvestigatorAdapter):
            logger.warning(
                f"Investigator adapter {model_name} failed claim validation (score: {groundedness_score}). "
                f"Falling back to deterministic TemplateInvestigatorAdapter."
            )
            final_report = self._template_adapter.generate_report(case, plan, tool_outputs, evidence_list)
            fallback_val = ClaimValidator.validate_report_claims(final_report, evidence_list)
            validator_passed = fallback_val.valid
            groundedness_score = fallback_val.groundedness_score
            unsupported = fallback_val.unsupported_claims
            model_name = f"{model_name}+fallback_to_template"

        latency_ms = round((time.time() - start_time) * 1000, 2)
        run_id = f"inv_{uuid.uuid4().hex[:12]}"
        now_iso = datetime.now(timezone.utc).isoformat()

        findings_summary = {
            "risk_score": case.risk_score,
            "decision": case.decision,
            "priority": case.priority.value,
            "groundedness_score": groundedness_score,
            "cited_evidence": validation_result.cited_evidence_verified
        }

        run_record = InvestigationRun(
            run_id=run_id,
            case_id=case_id,
            plan=plan,
            tool_calls=tool_calls,
            findings=findings_summary,
            report_text=final_report,
            provider=provider_name,
            model=model_name,
            prompt_hash=prompt_hash,
            validator_passed=validator_passed,
            groundedness_score=groundedness_score,
            unsupported_claims=unsupported,
            latency_ms=latency_ms,
            created_at=now_iso
        )

        self.case_repo.save_investigation_run(run_record)

        # Record event in incident ledger if incident exists
        if self.incident_repo and case.incident_id:
            try:
                self.incident_repo.append_incident_event(
                    incident_id=case.incident_id,
                    event_type="investigator_run_completed",
                    actor_id="system_investigator",
                    actor_role="investigator",
                    payload={
                        "run_id": run_id,
                        "validator_passed": validator_passed,
                        "groundedness_score": groundedness_score,
                        "latency_ms": latency_ms
                    }
                )
            except Exception as e:
                logger.warning(f"Could not append investigator event to incident ledger: {e}")

        return run_record
