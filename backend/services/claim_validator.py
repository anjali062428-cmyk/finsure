"""
FinSure Claim Validation Engine
Enforces strict factual groundedness of all statements generated by the FinSure Investigator.
Requires:
1. Explicit citation of recorded evidence IDs [E1], [E2], etc.
2. Verified existence of cited evidence records in the case evidence store.
3. Matching of numeric amounts, device references, and facts against cited evidence metadata.
4. Advisory tone constraint: rejects autonomous verdicts or definitive declarations of fraud.
"""

import re
import logging
from typing import List, Dict, Any, Set, Tuple, Optional

from backend.models.case import CaseEvidence, ClaimValidationResult

logger = logging.getLogger("finsure.claim_validator")

# Regex to capture citations like [E1], [E2], [E1, E3], [E1,E2]
CITATION_REGEX = re.compile(r"\[(E\d+(?:,\s*E\d+)*)\]")

# Unacceptable definitive/autonomous fraud assertions
PROHIBITED_ASSERTIONS = [
    r"\b100%\s+confirmed\s+fraud\b",
    r"\buser\s+is\s+guilty\b",
    r"\bverdict\s*:\s*fraud\b",
    r"\bi\s+have\s+decided\s+to\s+block\b",
    r"\bi\s+am\s+confirming\s+fraud\b",
    r"\bdefinitively\s+fraudulent\b",
    r"\bconclusive\s+proof\s+of\s+criminal\b"
]


class ClaimValidator:
    """Validates investigator draft claims against recorded case evidence."""

    @classmethod
    def validate_report_claims(
        cls,
        text: str,
        evidence_list: List[CaseEvidence]
    ) -> ClaimValidationResult:
        """
        Validates text against active evidence records.
        Returns ClaimValidationResult with detailed grounding breakdown.
        """
        if not text or not text.strip():
            return ClaimValidationResult(
                valid=False,
                groundedness_score=0.0,
                supported_claims=[],
                unsupported_claims=["Empty report content"],
                rejection_reasons=["Report text is empty."],
                cited_evidence_verified=[]
            )

        # Build map of active evidence
        active_evidence: Dict[str, CaseEvidence] = {
            ev.evidence_id: ev for ev in evidence_list if ev.withdrawn_at is None
        }

        # Check for prohibited autonomous assertions across entire text
        rejection_reasons = []
        for pattern in PROHIBITED_ASSERTIONS:
            if re.search(pattern, text, re.IGNORECASE):
                rejection_reasons.append(
                    f"Investigator violation: Text contains definitive autonomous fraud assertion matching '{pattern}'. "
                    "All findings must remain advisory ('Findings suggest...', 'Evidence indicates...')."
                )

        # Split text into sentences / factual statements
        sentences = cls._split_into_sentences(text)
        supported_claims: List[str] = []
        unsupported_claims: List[str] = []
        all_cited_ev_ids: Set[str] = set()

        for sentence in sentences:
            sentence_clean = sentence.strip()
            if not sentence_clean:
                continue

            # Skip header lines, greetings, or disclaimer sections that are not factual claims
            if cls._is_non_factual_line(sentence_clean):
                continue

            citations = cls._extract_citations(sentence_clean)
            if not citations:
                unsupported_claims.append(sentence_clean)
                rejection_reasons.append(
                    f"Missing citation: Statement contains factual assertions without evidence citation: '{sentence_clean}'"
                )
                continue

            # Verify citations exist in active evidence
            invalid_citations = [cid for cid in citations if cid not in active_evidence]
            if invalid_citations:
                unsupported_claims.append(sentence_clean)
                rejection_reasons.append(
                    f"Invalid evidence reference: Statement references non-existent or withdrawn evidence {invalid_citations}: '{sentence_clean}'"
                )
                continue

            # Verify numerical / fact consistency against cited evidence metadata
            valid_facts, fact_error = cls._verify_fact_consistency(sentence_clean, citations, active_evidence)
            if not valid_facts:
                unsupported_claims.append(sentence_clean)
                rejection_reasons.append(f"Fact inconsistency: {fact_error} in '{sentence_clean}'")
                continue

            # Claim passed all checks
            supported_claims.append(sentence_clean)
            all_cited_ev_ids.update(citations)

        total_claims = len(supported_claims) + len(unsupported_claims)
        if total_claims == 0:
            score = 1.0 if not rejection_reasons else 0.0
            is_valid = len(rejection_reasons) == 0
        else:
            score = round(len(supported_claims) / total_claims, 4)
            is_valid = (len(unsupported_claims) == 0) and (len(rejection_reasons) == 0)

        return ClaimValidationResult(
            valid=is_valid,
            groundedness_score=score,
            supported_claims=supported_claims,
            unsupported_claims=unsupported_claims,
            rejection_reasons=rejection_reasons,
            cited_evidence_verified=sorted(list(all_cited_ev_ids))
        )

    @classmethod
    def _extract_citations(cls, sentence: str) -> List[str]:
        found = []
        matches = CITATION_REGEX.findall(sentence)
        for match in matches:
            for item in match.split(","):
                item_clean = item.strip()
                if item_clean:
                    found.append(item_clean)
        return found

    @classmethod
    def _is_non_factual_line(cls, line: str) -> bool:
        lower = line.lower().strip()
        # Headings and structural titles (markdown #, ##, ###)
        if lower.startswith("#"):
            return True
        # Section titles with numbers e.g. "1. Case Summary", "2. Observed Evidence Breakdown"
        if re.match(r"^\d+\.\s+[A-Za-z\s]+$", line.strip()):
            return True
        # Headers ending in colon
        if lower.endswith(":") and len(line.split()) < 6:
            return True
        # Disclaimers and metadata banners
        if lower.startswith(("alert ->", "disclaimer", "note:", "reviewed by", "case:", "status:")):
            return True
        if "sole decision authority" in lower or "assistive only" in lower:
            return True
        # Questions are inquiries, not factual claims
        if lower.endswith("?"):
            return True
        # Checklist / to-do items under missing evidence or action recommendations
        if lower.startswith(("- direct customer", "- beneficiary account", "- out-of-band", "- verify ")):
            return True
        # General advisory guidance
        if "analyst review is recommended" in lower or "investigation recommended" in lower:
            return True
        return False

    @classmethod
    def _split_into_sentences(cls, text: str) -> List[str]:
        lines = text.split("\n")
        sentences = []
        for line in lines:
            line_str = line.strip()
            if not line_str:
                continue
            # If the whole line is non-factual (header, disclaimer, question, etc.), skip before splitting
            if cls._is_non_factual_line(line_str):
                continue

            # If line is a bullet point or numbered item
            if line_str.startswith(("-", "*", "•")) or re.match(r"^\d+\.\s+", line_str):
                content = re.sub(r"^[-*•\d\.\s]+", "", line_str).strip()
                if content and not cls._is_non_factual_line(content):
                    sentences.append(content)
            else:
                # Regular paragraph: split by period followed by space, but only if preceded by 2+ word characters (avoid splitting on "1.", "Dr.", etc.)
                parts = re.split(r"(?<=[a-zA-Z0-9\]\)])[.!?]\s+", line_str)
                for p in parts:
                    p_clean = p.strip().rstrip(".")
                    if p_clean and not cls._is_non_factual_line(p_clean):
                        sentences.append(p_clean)
        return sentences

    @classmethod
    def _verify_fact_consistency(
        cls,
        sentence: str,
        citations: List[str],
        active_evidence: Dict[str, CaseEvidence]
    ) -> Tuple[bool, Optional[str]]:
        """
        Cross-checks numbers/amounts in the sentence against metadata in the cited evidence.
        """
        # Look for currency amounts e.g., ₹50,000, Rs. 50000, 50,000 INR
        amounts = re.findall(r"(?:₹|Rs\.?)\s*([0-9,]+(?:\.[0-9]+)?)", sentence)
        for amt_str in amounts:
            try:
                amt_val = float(amt_str.replace(",", ""))
                # Check if this amount appears in any cited evidence metadata
                matched = False
                for cid in citations:
                    ev = active_evidence[cid]
                    ev_meta_str = str(ev.metadata)
                    if str(amt_val) in ev_meta_str or amt_str.replace(",", "") in ev_meta_str:
                        matched = True
                        break
                    if "amount" in ev.metadata and abs(float(ev.metadata["amount"]) - amt_val) < 0.01:
                        matched = True
                        break
                if not matched:
                    return False, f"Mentioned amount {amt_str} is not found in cited evidence metadata {citations}"
            except ValueError:
                continue

        return True, None
